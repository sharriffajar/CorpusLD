def get_clean_schema_org_jsonld(data: Dict[str, Any]) -> Dict[str, Any]:
    """
    Menghasilkan JSON-LD murni 100% kepatuhan standar Schema.org (tanpa field ad-hoc, pagination, atau mentions)
    yang dijamin lolos validator.schema.org dan Google Rich Results Test.
    """
    allowed_keys = {
        "@context", "@type", "@id", "name", "headline", "alternateName",
        "description", "inLanguage", "datePublished", "dateModified",
        "keywords", "author", "creator", "publisher", "sdPublisher", "about", "hasPart",
        "additionalProperty", "citation", "action", "potentialAction",
        "mainEntity", "encodingFormat", "url", "identifier", "sameAs"
    }
    
    def _prune(val: Any) -> Any:
        if isinstance(val, dict):
            c = {}
            for k, v in val.items():
                cleaned_v = _prune(v)
                if cleaned_v is not None and cleaned_v != "" and cleaned_v != [] and cleaned_v != {}:
                    c[k] = cleaned_v
            return c
        elif isinstance(val, list):
            cleaned_l = [_prune(x) for x in val]
            return [x for x in cleaned_l if x is not None and x != "" and x != [] and x != {}]
        return val

    clean = {}
    for k, v in data.items():
        if k in allowed_keys:
            cleaned_val = _prune(v)
            if cleaned_val is not None and cleaned_val != "" and cleaned_val != [] and cleaned_val != {}:
                clean[k] = cleaned_val
                
    if "@context" not in clean:
        clean["@context"] = "https://schema.org"
    return clean


def generate_google_scholar_meta_tags(
    data: Dict[str, Any],
    pdf_url: Optional[str] = None,
    abstract_url: Optional[str] = None,
    fulltext_world_readable: bool = True
) -> str:
    """
    Menghasilkan baris HTML meta tags Google Scholar & Highwire Press standar resmi (Cheat Sheet lengkap).
    Memungkinkan publikasi ilmiah terindeks otomatis oleh Google Scholar, Semantic Scholar, Crossref, dan Zotero.
    """
    lines = [
        "<!-- Google Scholar & Academic Discoverability Meta Tags (Generated by CorpusLD) -->"
    ]
    title = data.get("name") or data.get("headline") or ""
    if title:
        lines.append(f'<meta name="citation_title" content="{html.escape(str(title))}">')
    
    authors = data.get("author", [])
    if isinstance(authors, list):
        for auth in authors:
            if isinstance(auth, dict):
                name = auth.get("name", "")
                if name:
                    lines.append(f'<meta name="citation_author" content="{html.escape(str(name))}">')
                    aff = auth.get("affiliation")
                    if aff:
                        if isinstance(aff, list):
                            for aff_item in aff:
                                aff_name = aff_item.get("name", "") if isinstance(aff_item, dict) else str(aff_item)
                                if aff_name:
                                    lines.append(f'<meta name="citation_author_institution" content="{html.escape(str(aff_name))}">')
                        else:
                            aff_name = aff.get("name", "") if isinstance(aff, dict) else str(aff)
                            if aff_name:
                                lines.append(f'<meta name="citation_author_institution" content="{html.escape(str(aff_name))}">')
            elif isinstance(auth, str) and auth.strip():
                lines.append(f'<meta name="citation_author" content="{html.escape(auth.strip())}">')

    date = data.get("datePublished")
    if date:
        date_slash = str(date).replace("-", "/")
        lines.append(f'<meta name="citation_publication_date" content="{html.escape(date_slash)}">')
        lines.append(f'<meta name="citation_online_date" content="{html.escape(date_slash)}">')
    else:
        lines.append('<!-- <meta name="citation_publication_date" content="YYYY/MM/DD"> (Date not identified in PDF, fill manually if needed) -->')

    # Journal / Periodical container metadata
    journal_name = ""
    part_of = data.get("isPartOf")
    if isinstance(part_of, dict) and part_of.get("name"):
        journal_name = str(part_of["name"])
    elif isinstance(data.get("publisher"), dict) and data.get("publisher", {}).get("note") == "inferred-journal":
        journal_name = str(data["publisher"]["name"])
    if journal_name:
        lines.append(f'<meta name="citation_journal_title" content="{html.escape(journal_name)}">')

    vol = data.get("volumeNumber") or (part_of.get("volumeNumber") if isinstance(part_of, dict) else None)
    if vol:
        lines.append(f'<meta name="citation_volume" content="{html.escape(str(vol))}">')

    issue = data.get("issueNumber") or (part_of.get("issueNumber") if isinstance(part_of, dict) else None)
    if issue:
        lines.append(f'<meta name="citation_issue" content="{html.escape(str(issue))}">')

    first_page = data.get("pageStart")
    if first_page:
        lines.append(f'<meta name="citation_firstpage" content="{html.escape(str(first_page))}">')
        
    last_page = data.get("pageEnd")
    if last_page:
        lines.append(f'<meta name="citation_lastpage" content="{html.escape(str(last_page))}">')

    # DOI resmi dokumen -> citation_doi
    doi_val = ""
    for ident in (data.get("identifier") or []):
        if isinstance(ident, dict) and str(ident.get("propertyID", "")).upper() == "DOI" and ident.get("value"):
            doi_val = str(ident["value"]).strip()
            break
    if not doi_val and data.get("sameAs"):
        m_same = re.match(r'https?://(?:dx\.)?doi\.org/(10\.\S+)', str(data["sameAs"]))
        if m_same:
            doi_val = m_same.group(1)
    if doi_val:
        lines.append(f'<meta name="citation_doi" content="{html.escape(doi_val)}">')

    # ISSN
    issn_val = data.get("issn")
    if not issn_val:
        for ident in (data.get("identifier") or []):
            if isinstance(ident, dict) and "ISSN" in str(ident.get("propertyID", "")).upper() and ident.get("value"):
                issn_val = str(ident["value"]).strip()
                break
    if issn_val:
        lines.append(f'<meta name="citation_issn" content="{html.escape(str(issn_val))}">')

    # PDF and Abstract URLs
    if pdf_url:
        lines.append(f'<meta name="citation_pdf_url" content="{html.escape(pdf_url)}">')
    elif isinstance(data.get("encoding"), dict) and data.get("encoding", {}).get("contentUrl"):
        lines.append(f'<meta name="citation_pdf_url" content="{html.escape(str(data["encoding"]["contentUrl"]))}">')

    if abstract_url:
        lines.append(f'<meta name="citation_abstract_html_url" content="{html.escape(abstract_url)}">')
    elif data.get("url"):
        lines.append(f'<meta name="citation_abstract_html_url" content="{html.escape(str(data["url"]))}">')

    pub = data.get("publisher")
    if isinstance(pub, dict) and pub.get("name") and pub.get("note") != "inferred-journal":
        lines.append(f'<meta name="citation_publisher" content="{html.escape(str(pub["name"]))}">')

    lang = data.get("inLanguage", "id")
    if lang:
        lines.append(f'<meta name="citation_language" content="{html.escape(str(lang))}">')

    keywords = data.get("keywords", [])
    if keywords:
        kw_str = "; ".join(keywords) if isinstance(keywords, list) else str(keywords)
        lines.append(f'<meta name="citation_keywords" content="{html.escape(kw_str)}">')

    desc = data.get("description", "")
    if desc:
        lines.append(f'<meta name="citation_abstract" content="{html.escape(str(desc))}">')

    if fulltext_world_readable:
        lines.append('<meta name="citation_fulltext_world_readable" content="">')

    citations = data.get("citation", []) or data.get("references_or_sources", [])
    if isinstance(citations, list):
        for ref in citations:
            if isinstance(ref, str) and len(ref.strip()) > 10:
                lines.append(f'<meta name="citation_reference" content="{html.escape(ref.strip())}">')

    return "\n".join(lines)


def generate_html_head_package(
    data: Dict[str, Any],
    pdf_url: Optional[str] = None,
    abstract_url: Optional[str] = None,
    fulltext_world_readable: bool = True
) -> str:
    """
    Menghasilkan satu paket lengkap tag <head> HTML yang valid untuk web hosting / CMS jurnal.
    Menggabungkan Charset, Viewport, Google Scholar Meta Tags (Highwire Press), dan Schema.org JSON-LD secara terintegrasi.
    """
    title = html.escape(str(data.get("name") or data.get("headline") or "Academic Publication"))
    scholar_tags = generate_google_scholar_meta_tags(
        data,
        pdf_url=pdf_url,
        abstract_url=abstract_url,
        fulltext_world_readable=fulltext_world_readable
    )
    
    indented_meta = "\n".join("  " + l if l.strip() else "" for l in scholar_tags.split("\n"))
    clean_json = get_clean_schema_org_jsonld(data)
    json_ld_str = json.dumps(clean_json, indent=2, ensure_ascii=False)
    indented_json = "\n".join("    " + l for l in json_ld_str.split("\n"))
    
    html_bundle = f"""<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>{title}</title>

{indented_meta}

  <!-- Schema.org Academic Knowledge Graph (JSON-LD) -->
  <script type="application/ld+json">
{indented_json}
  </script>
</head>"""
    return html_bundle


